//! Lifecycle/configuration only. The published ascii-reveal package owns all glyphs and animation.
use leptos::{html, prelude::*};
use wasm_bindgen::prelude::*;

#[wasm_bindgen(module = "/node_modules/ascii-reveal/dist/core.js")]
extern "C" {
    #[wasm_bindgen(js_name = asciiSkeletonHTML)]
    fn skeleton_html(options: &JsValue) -> String;
    #[wasm_bindgen(js_name = animateSkeletons)]
    fn animate_skeletons(root: &web_sys::HtmlElement) -> js_sys::Function;
    #[wasm_bindgen(js_name = createAsciiReveal)]
    fn create_reveal(root: &web_sys::HtmlElement, options: &JsValue) -> Controller;
    type Controller;
    #[wasm_bindgen(method)]
    fn reveal(this: &Controller) -> js_sys::Promise;
    #[wasm_bindgen(method)]
    fn destroy(this: &Controller);
    #[wasm_bindgen(thread_local_v2, js_name = SKELETON_CSS)]
    static SKELETON_CSS: String;
}

fn options(value: serde_json::Value) -> JsValue {
    js_sys::JSON::parse(&value.to_string()).expect("static ascii-reveal configuration")
}

/// Honor both the OS preference and Tickets' in-app override, including changes mid-animation.
fn reduced_motion() -> RwSignal<bool> {
    let reduced = RwSignal::new(false);
    let query = window()
        .match_media("(prefers-reduced-motion: reduce)")
        .ok()
        .flatten();
    let read = move || {
        document()
            .document_element()
            .is_some_and(|root| root.get_attribute("data-motion").as_deref() == Some("reduce"))
            || window()
                .match_media("(prefers-reduced-motion: reduce)")
                .ok()
                .flatten()
                .is_some_and(|m| m.matches())
    };
    reduced.set(read());
    let change = Closure::<dyn FnMut()>::new(move || reduced.set(read()));
    if let Some(query) = &query {
        let _ = query.add_event_listener_with_callback("change", change.as_ref().unchecked_ref());
    }
    let observer = web_sys::MutationObserver::new(change.as_ref().unchecked_ref()).ok();
    if let (Some(observer), Some(root)) = (&observer, document().document_element()) {
        let config = web_sys::MutationObserverInit::new();
        config.set_attribute_filter(&js_sys::Array::of1(&"data-motion".into()));
        config.set_attributes(true);
        let _ = observer.observe_with_options(&root, &config);
    }
    let change = StoredValue::new_local(change);
    on_cleanup(move || {
        if let Some(query) = query {
            change.with_value(|change| {
                let _ = query
                    .remove_event_listener_with_callback("change", change.as_ref().unchecked_ref());
            });
        }
        if let Some(observer) = observer {
            observer.disconnect();
        }
    });
    reduced
}

#[component]
pub fn AsciiStyles() -> impl IntoView {
    view! { <style>{SKELETON_CSS.with(Clone::clone)}</style> }
}

/// `rows` makes a block; `lines` makes a paragraph. Markup is generated by the package only.
#[component]
pub fn AsciiSkeleton(
    #[prop(default = "scan")] variant: &'static str,
    #[prop(default = 3)] lines: u32,
    #[prop(optional)] rows: Option<u32>,
    #[prop(default = "")] class: &'static str,
) -> impl IntoView {
    let root = NodeRef::<html::Span>::new();
    let reduced = reduced_motion();
    let mut config = serde_json::json!({"variant": variant, "lines": lines, "css": false});
    if let Some(rows) = rows {
        config["rows"] = rows.into();
    }
    let markup = skeleton_html(&options(config));
    Effect::new(move |_| {
        if let Some(root) = root.get()
            && !reduced.get()
        {
            let stop = animate_skeletons(&root);
            on_cleanup(move || {
                let _ = stop.call0(&JsValue::NULL);
            });
        }
    });
    view! { <span node_ref=root class=format!("ascii-skeleton {class}") aria-hidden="true" inner_html=markup/> }
}

/// Attach to an existing layout root so loading feedback never adds layout wrappers.
/// Replay only after a pending -> ready transition, or once on mount when requested.
pub fn use_ascii_reveal<E>(root: NodeRef<E>, pending: Signal<bool>, on_mount: bool)
where
    E: html::ElementType,
    E::Output: AsRef<web_sys::HtmlElement> + Clone + JsCast,
{
    let reduced = reduced_motion();
    let mut was_pending = on_mount;
    Effect::new(move |_| {
        let pending = pending.get();
        let reduced = reduced.get();
        let root = root.get();
        // Mark every host before the package can append its overlay. Geometry
        // ships in foundation.css, independently of the package's lazy styles.
        if let Some(root) = &root {
            let element: &web_sys::HtmlElement = root.as_ref();
            let _ = element.set_attribute("data-ascii-root", "");
        }
        if pending {
            was_pending = true;
            return;
        }
        if let Some(root) = root
            && was_pending
        {
            was_pending = false;
            if reduced {
                return;
            }
            let controller = create_reveal(
                root.as_ref(),
                &options(serde_json::json!({
                    "preset": "decode", "duration": "fast", "speed": 1.25,
                    "origin": "top-left", "lazy": false,
                    "fades": ".busy-button, [data-ascii=fade]",
                    "media": "[data-ascii-media]"
                })),
            );
            // The library keeps semantic text in place and draws a decorative overlay.
            let _ = controller.reveal();
            on_cleanup(move || controller.destroy());
        }
    });
}

#[component]
pub fn AsciiReveal(children: Children, #[prop(default = "")] class: &'static str) -> impl IntoView {
    let root = NodeRef::<html::Div>::new();
    use_ascii_reveal(root, Signal::derive(|| false), true);
    view! { <div node_ref=root class=class>{children()}</div> }
}

#[component]
pub fn LoadingIndicator(#[prop(default = "Loading")] label: &'static str) -> impl IntoView {
    view! { <span class="loading-indicator" role="status" aria-live="polite"><AsciiSkeleton lines=1/><span class="sr-only">{label}</span></span> }
}

#[component]
pub fn LoadingSkeleton(#[prop(default = "board")] layout: &'static str) -> impl IntoView {
    let label = match layout {
        "detail" => "Loading ticket…",
        "projects" => "Loading projects…",
        _ => "Loading tickets…",
    };
    view! {<div class=format!("loading-skeleton loading-{layout}") role="status" aria-label=label aria-busy="true"><div class="loading-caption">{label}</div><div class="skeleton-layout" aria-hidden="true">{match layout {
        "board"=>(0..4).map(|_|view!{<div class="skeleton-column"><AsciiSkeleton lines=1 class="skeleton-heading"/>{(0..3).map(|_|view!{<div class="skeleton-card"><AsciiSkeleton lines=3/></div>}).collect_view()}</div>}).collect_view().into_any(),
        "detail"=>view!{<div class="skeleton-detail detail-layout"><div class="ticket-detail"><AsciiSkeleton lines=1 class="skeleton-heading"/><AsciiSkeleton lines=4/><div class="skeleton-section"><AsciiSkeleton lines=4/></div></div><aside class="properties"><AsciiSkeleton lines=6/></aside></div>}.into_any(),
        _=>(0..7).map(|_|view!{<div class="skeleton-row"><AsciiSkeleton lines=1/></div>}).collect_view().into_any(),
    }}</div></div>}
}
